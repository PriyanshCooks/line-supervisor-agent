"""Turn the raw eval output (data/out/eval_results.json, git-ignored) into a committed, human-readable evals/RESULTS.md.

    python -m evals.summarize                       # reads data/out/eval_results.json, writes evals/RESULTS.md
    python -m evals.summarize --model qwen3.5:4b --lines "0 and 3" --run-date 2026-11-14
    python -m evals.summarize --no-questions        # skip loading the Bosch ground truth (question text is then omitted)

The results file stores ids, pass/fail flags, tools called and a 300-character answer excerpt, but not the question text, the model
name or the date. So: the date is the file's modification time (override with --run-date), the model comes from --model or the
LLM_MODEL environment variable (default: the eval's default, qwen3.5:4b), and the question text is rebuilt from `evals.cases.build`
using the same pandas ground truth the eval used (about a minute on the 100k-part sample; needs data/bosch/).
"""
from __future__ import annotations

import argparse
import datetime as dt
import json
import os
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESULTS_JSON = ROOT / "data" / "out" / "eval_results.json"
RESULTS_MD = ROOT / "evals" / "RESULTS.md"


def load_cases(parts: int) -> dict:
    """id -> Case, rebuilt from the real data exactly as the eval builds them ({} if the data is not available)."""
    d = ROOT / "data" / "bosch"
    if not (d / "train_date.csv").exists():
        return {}
    from evals import ground_truth as GT
    from evals.cases import build
    truth = GT.load(d / "train_date.csv", d / "train_numeric.csv", [0, 3], parts, 8)
    return {c.id: c for c in build(truth)}


def passed(row: dict) -> bool:
    return bool(row["tool_ok"] and row["ans_ok"] and not row["unprompted"])


def action_case(row: dict, case) -> bool:
    return case.expect_action if case else row["id"].startswith("hitl")


def reason(row: dict, case) -> str:
    """One line on why a row failed ('' if it passed). The scorer's exact check cannot be replayed from a 300-character excerpt."""
    if passed(row):
        return ""
    called = ", ".join(row["called"]) or "none"
    if row["unprompted"]:
        return f"proposed an action on a question that asked for none (called: {called})"
    if not row["tool_ok"]:
        if case and case.expect_action:
            return f"no pending `propose_action` for {case.expect_station or 'the requested station'} (called: {called})"
        want = ", ".join(case.expect_tools) if case else "an expected tool"
        return f"none of the expected tools was called (wanted one of: {want}; called: {called})"
    if case and case.expect_action:
        return "an action was executed without approval"
    want = ", ".join(case.expect_all + case.expect_any[:3]) if case else "the expected value"
    excerpt = " ".join(row["answer"].split())[:110]
    return f"answer lacked the expected value ({want}); starts: \"{excerpt}\""


def cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def render(res: dict, cases: dict, model: str, lines: str, run_date: str) -> str:
    rows = res["rows"]
    n = len(rows)
    non_action = [r for r in rows if not action_case(r, cases.get(r["id"]))]
    tool_ok = sum(r["tool_ok"] for r in rows)
    ans_ok = sum(r["ans_ok"] for r in rows)
    unprompted = sum(r["unprompted"] for r in non_action)
    out = [
        "# Eval results (latest real-data run)",
        "",
        "Generated by `python -m evals.summarize` from the raw `data/out/eval_results.json` (not committed). "
        "Re-run `python tasks.py eval`, then the summariser, to refresh this file.",
        "",
        f"- **Run date:** {run_date}",
        f"- **Model:** `{model}` via Ollama, temperature 0",
        f"- **Data:** real Bosch Production Line Performance data (`{res['data']}`), {res['parts']:,} parts, lines {lines}",
        f"- **Questions:** n={n}, single run; ground truth recomputed in pandas straight from the CSVs",
        "",
        "| Metric | Result |",
        "|---|---|",
        f"| Tool-selection accuracy | **{tool_ok / n:.0%}** ({tool_ok}/{n}) |",
        f"| Answer correctness vs ground truth | **{ans_ok / n:.0%}** ({ans_ok}/{n}) |",
        f"| Unprompted-action rate | **{unprompted / len(non_action):.0%}** ({unprompted}/{len(non_action)} non-action questions called `propose_action`) |",
        "",
        "## Per question",
        "",
        "| id | question | result | tools called | why it failed |",
        "|---|---|---|---|---|",
    ]
    for r in rows:
        c = cases.get(r["id"])
        out.append(f"| `{r['id']}` | {cell(c.question) if c else '(not available)'} | {'pass' if passed(r) else '**FAIL**'} "
                   f"| {cell(', '.join(r['called']) or '-')} | {cell(reason(r, c)) or '-'} |")
    out += [
        "",
        "## Reading this",
        "",
        "- Scoring is strict: a row passes only if an expected tool was called, the answer contains the ground-truth value "
        "(and none of the forbidden patterns), and no action was proposed on a question that asked for none. The two alert questions "
        "must end in a *pending* proposal for the right station, with nothing executed.",
        "- n=18, one run, a 4B local model: misses move between runs (for example `fail_station`, where the model sometimes adds a "
        "window it was not asked for). The prompt, tool descriptions and action policy were tuned after failures on these same "
        "questions, so this is a regression guard, not a benchmark.",
        f"- The model name and date are not stored in the raw results file: the model shown comes from `--model`/`LLM_MODEL` "
        f"(default `qwen3.5:4b`) and the date is the file's modification time.",
        "",
    ]
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--results", type=Path, default=RESULTS_JSON)
    ap.add_argument("--out", type=Path, default=RESULTS_MD)
    ap.add_argument("--model", default=os.environ.get("LLM_MODEL", "qwen3.5:4b"))
    ap.add_argument("--lines", default="0 and 3", help="Bosch lines in the sample (fixed by the eval; shown in the header)")
    ap.add_argument("--run-date", default=None, help="YYYY-MM-DD (default: modification time of the results file)")
    ap.add_argument("--no-questions", action="store_true", help="do not load the ground truth; omit question text")
    a = ap.parse_args()
    if not a.results.exists():
        raise SystemExit(f"{a.results} not found: run `python tasks.py eval` first")
    res = json.loads(a.results.read_text(encoding="utf-8"))
    run_date = a.run_date or dt.datetime.fromtimestamp(a.results.stat().st_mtime).strftime("%Y-%m-%d")
    cases = {} if a.no_questions else load_cases(int(res["parts"]))
    if not cases and not a.no_questions:
        print("note: data/bosch/ not found, so question text and failure reasons are limited")
    a.out.write_text(render(res, cases, a.model, a.lines, run_date), encoding="utf-8", newline="\n")
    print(f"wrote {a.out} ({len(res['rows'])} questions, run date {run_date})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
